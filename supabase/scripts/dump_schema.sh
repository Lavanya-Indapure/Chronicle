#!/usr/bin/env bash
# Dumps Chronicle's database schema (DDL only — no rows) into supabase/schema/.
#
#   bash supabase/scripts/dump_schema.sh
#
# Needs Docker (pg_dump must be at least the server's major version, so it
# runs from the official postgres image instead of a local install) and
# SUPABASE_DB_URL in supabase/.env — see supabase/.env.example.
#
# Output (commit these; re-run after every schema change):
#   schema/extensions.sql  extensions the database uses
#   schema/public.sql      tables, constraints, indexes, functions, triggers,
#                          RLS policies of the app's own `public` schema
#   schema/storage.sql     storage buckets and their access policies
set -euo pipefail

cd "$(dirname "$0")/.."

if [ -f .env ]; then
  set -a
  # shellcheck disable=SC1091
  . ./.env
  set +a
fi
: "${SUPABASE_DB_URL:?Set SUPABASE_DB_URL in supabase/.env (copy .env.example)}"

PG_IMAGE="${PG_IMAGE:-postgres:17}"
OUT=schema
mkdir -p "$OUT"

# Runs a postgres client tool from the image. The URL is passed as an env var
# so it never shows up in the process list or shell history.
pg() {
  docker run --rm -i -e PGCONNECT_TIMEOUT=20 -e DB_URL="$SUPABASE_DB_URL" "$PG_IMAGE" \
    sh -c "$1"
}

header() {
  printf -- '-- %s\n-- Generated by supabase/scripts/dump_schema.sh — do not edit by hand.\n\n' "$1"
}

echo "→ extensions"
{
  header "Extensions used by the database"
  pg 'psql "$DB_URL" -X -At -v ON_ERROR_STOP=1' <<'SQL'
select format('create extension if not exists %I with schema %I;', e.extname, n.nspname)
from pg_extension e
join pg_namespace n on n.oid = e.extnamespace
where e.extname <> 'plpgsql'
order by e.extname;
SQL
} > "$OUT/extensions.sql"

echo "→ public schema"
{
  header "App schema: tables, constraints, indexes, functions, triggers, RLS policies"
  # --restrict-key keeps the output identical between runs (no random token).
  pg 'pg_dump "$DB_URL" --schema-only --schema=public --no-owner --no-privileges --restrict-key=chronicle'
} > "$OUT/public.sql"

echo "→ storage buckets & policies"
{
  header "Storage: buckets and storage.objects policies (Supabase owns the tables)"
  pg 'psql "$DB_URL" -X -At -v ON_ERROR_STOP=1' <<'SQL'
select format(
  'insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %s, %s, %L) on conflict (id) do nothing;',
  id, name, public, coalesce(file_size_limit::text, 'null'), allowed_mime_types)
from storage.buckets
order by id;

select format(
  E'drop policy if exists %I on storage.objects;\ncreate policy %I on storage.objects as %s for %s to %s%s%s;\n',
  policyname, policyname, permissive, cmd, array_to_string(roles, ', '),
  case when qual is not null then E'\n  using (' || qual || ')' else '' end,
  case when with_check is not null then E'\n  with check (' || with_check || ')' else '' end)
from pg_policies
where schemaname = 'storage' and tablename = 'objects'
order by policyname;
SQL
} > "$OUT/storage.sql"

echo "✓ wrote $(cd "$OUT" && pwd)"
wc -l "$OUT"/*.sql
